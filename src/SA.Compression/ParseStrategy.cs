namespace SA.Compression;

/// <summary>
/// Стратегії синтаксичного розбору вхідного потоку для базового рівня ролі П1.
/// </summary>
public enum ParseStrategy
{
    /// <summary>
    /// Жадібний алгоритм: у кожній позиції хапає найдовший збіг, знайдений одразу.
    /// </summary>
    Greedy,

    /// <summary>
    /// Лінивий алгоритм: якщо в наступній позиції є довший збіг — відкладає поточний, 
    /// видаючи один літерал, щоб на наступному кроці взяти довший шматок.
    /// </summary>
    Lazy,
}