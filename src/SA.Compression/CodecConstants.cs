namespace SA.Compression;

/// <summary>
/// Глобальні константи формату стиснення зі специфікації FORMAT_SPEC_P2 (розділи 3 і 6).
/// Ці числові значення є стандартом формату і не підлягають зміні.
/// </summary>
public static class CodecConstants
{
    // Мінімальна довжина повтору (збігу) для алгоритму LZ77:
    // посилання на меншу кількість байтів записувати невигідно через накладні витрати на адресу
    public const int MinMatch = 3;

    // Максимальна довжина одного повтору за специфікацією (відповідає лімітам кодування довжини)
    public const int MaxMatch = 258;

    // Розмір ковзного вікна LZ77 (32 КБ): на таку максимальну відстань назад можна посилатися
    public const int WindowSize = 32768;

    // Максимально дозволена глибина/довжина бітового коду в канонічному дереві Гаффмана (15 біт)
    public const int MaxCodeLength = 15;

    // Розмір алфавіту літералів LIT:
    // 0..255 — сирі байти даних, 256 — спеціальний маркер MatchMarker («початок LZ77-посилання»)
    public const int LitAlphabetSize = 257;

    // Розмір алфавіту довжин збігів LEN: кодує різницю (length - MinMatch), тобто 0..255 для довжин 3..258
    public const int LenAlphabetSize = 256;

    // Розмір алфавіту кодів відстаней DIST: визначає порядок/діапазон відстані (від 0 до 15)
    public const int DistAlphabetSize = 16;

    // Спеціальний символ алфавіту LIT (код 256), який вказує декодеру: «далі йде не байт, а LZ77-посилання»
    public const int MatchMarker = 256;

    // Орієнтовна фіксована вартість запису одного літерала в бітах (розділ 6: використовується для DP-розбору)
    public const int LiteralCostBits = 9;

    // Базова фіксована вартість запису LZ77-посилання в бітах (маркер + довжина + код відстані)
    public const int ReferenceBaseCostBits = 17;
}